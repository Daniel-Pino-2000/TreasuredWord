"""Builds app/src/main/res/drawable/splash_icon_{light,dark}.xml (#151, #161).

The startup screen's icon is the launcher's book on its espresso circle with the app's name under
it. It used to be a layer-list of insets around ic_launcher_foreground and splash_wordmark_*, but
Android only draws that on a launch it builds the startup screen for from scratch (the first after
an install or a light/dark or rotation change). Later launches reuse a cached startup screen that
can't draw a layer-list and fall back to the plain launcher icon, without the name. Seen on a
Pixel emulator (Android 16) every time, and as #151 on a Galaxy S23 (Android 17).
A single vector works on every launch, so this script copies the same parts, at the same places,
into one 288 dp vector.

Run it again after changing the launcher's ic_launcher_foreground.xml or the splash_wordmark_*.xml
sources next to this script:
    python docs/icon-source/make_splash_icons.py
"""
import copy
import pathlib
import xml.etree.ElementTree as ET

ANDROID = "http://schemas.android.com/apk/res/android"
AAPT = "http://schemas.android.com/aapt"
TOOLS = "http://schemas.android.com/tools"
ET.register_namespace("android", ANDROID)
ET.register_namespace("aapt", AAPT)
ET.register_namespace("tools", TOOLS)

HERE = pathlib.Path(__file__).resolve().parent
RES = HERE.parents[1] / "app" / "src" / "main" / "res" / "drawable"

# The icon area of a startup screen without an icon background is 288 dp, of which the system
# shows the 192 dp circle in the middle. Same layout as the old layer-list:
SIZE = 288
CIRCLE = (144, 130, 58)              # centre x, centre y, radius: a 116 dp circle, its top 72 dp down
BOOK = (57, 43, 174)                 # left, top, size: the launcher's 72 dp visible area fills the circle
NAME = (59, 172.5, 0.85)             # left, top, scale: the name at 85%, 12 dp below the circle


def a(name):
    return f"{{{ANDROID}}}{name}"


def parts(path):
    """The drawing elements of a vector drawable, and its viewport width and height."""
    root = ET.parse(path).getroot()
    return list(root), float(root.get(a("viewportWidth"))), float(root.get(a("viewportHeight")))


def group(children, x, y, scale_x, scale_y):
    g = ET.Element("group", {a("translateX"): f"{x:g}", a("translateY"): f"{y:g}",
                             a("scaleX"): f"{scale_x:.6g}", a("scaleY"): f"{scale_y:.6g}"})
    g.extend(copy.deepcopy(c) for c in children)
    return g


def build(mode):
    vector = ET.Element("vector", {a("width"): f"{SIZE}dp", a("height"): f"{SIZE}dp",
                                   a("viewportWidth"): str(SIZE), a("viewportHeight"): str(SIZE),
                                   f"{{{TOOLS}}}ignore": "VectorRaster,VectorPath"})
    cx, cy, r = CIRCLE
    vector.append(ET.Element("path", {
        a("fillColor"): "@color/splash_icon_background",
        a("pathData"): f"M{cx - r},{cy}a{r},{r} 0,1 1,{2 * r},0a{r},{r} 0,1 1,{-2 * r},0z",
    }))
    book, bw, bh = parts(RES / "ic_launcher_foreground.xml")
    x, y, size = BOOK
    vector.append(group(book, x, y, size / bw, size / bh))
    name, _, _ = parts(HERE / f"splash_wordmark_{mode}.xml")
    x, y, scale = NAME
    vector.append(group(name, x, y, scale, scale))

    ET.indent(vector, space="    ")
    body = ET.tostring(vector, encoding="unicode")
    header = (
        '<?xml version="1.0" encoding="utf-8"?>\n'
        f"<!-- Startup screen icon, {mode} mode (#143): the launcher's book on its espresso circle, with the\n"
        "     app's name under it. GENERATED by docs/icon-source/make_splash_icons.py from\n"
        f"     ic_launcher_foreground.xml and docs/icon-source/splash_wordmark_{mode}.xml; edit those and\n"
        "     run it again. One vector, not a layer-list: Android reuses a cached startup screen after\n"
        "     the first launch, and that one can't draw a layer-list, so it showed the plain launcher\n"
        "     icon (#151). VectorRaster: 288 dp is the size the system gives a startup icon. VectorPath:\n"
        "     the name's letter outlines are long, but the system draws them once per launch. -->\n"
    )
    (RES / f"splash_icon_{mode}.xml").write_text(header + body + "\n", encoding="utf-8")


for mode in ("light", "dark"):
    build(mode)
