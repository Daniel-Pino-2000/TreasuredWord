"""Builds every app-icon file from docs/icon-source/icon.svg (#368).

icon.svg is the one source. This script turns its three layers into the adaptive icon's vector
drawables, renders the PNGs, and rebuilds the startup-screen icons and the Play feature graphic:

    app/src/main/res/drawable/ic_launcher_background.xml   <- <g id="background">
    app/src/main/res/drawable/ic_launcher_foreground.xml   <- <g id="foreground">
    app/src/main/res/drawable/ic_launcher_monochrome.xml   <- <g id="monochrome">
    app/src/main/res/mipmap-*/ic_launcher{,_round}.png     <- Android 7 (minSdk 24) fallback
    docs/icon-source/playstore-icon-512.png                <- Play Console app icon
    app/src/main/res/drawable/splash_icon_{light,dark}.xml <- make_splash_icons.py
    docs/play-store/feature-graphic.{svg,png}              <- the book copied in, then rendered

Run it after editing icon.svg (or feature-graphic.svg):
    python docs/icon-source/make_icons.py

Free tools only: Python with Pillow, and Chrome or Edge in headless mode to draw the SVGs.
"""
import os
import pathlib
import re
import shutil
import subprocess
import tempfile
import xml.etree.ElementTree as ET

from PIL import Image, ImageDraw

import make_splash_icons

SVG_NS = "http://www.w3.org/2000/svg"
HERE = pathlib.Path(__file__).resolve().parent
ROOT = HERE.parents[1]
RES = ROOT / "app" / "src" / "main" / "res"
SOURCE = HERE / "icon.svg"
FEATURE = ROOT / "docs" / "play-store" / "feature-graphic.svg"

MIPMAPS = {"mdpi": 48, "hdpi": 72, "xhdpi": 96, "xxhdpi": 144, "xxxhdpi": 192}
RENDER = 1024  # px the 72-unit visible area is drawn at before scaling down


def tag(el):
    return el.tag.split("}")[-1] if isinstance(el.tag, str) else None


def num(v):
    return f"{float(v):g}"


def color(c):
    """#RGB / #RRGGBB to Android's #AARRGGBB."""
    c = c.lstrip("#")
    if len(c) == 3:
        c = "".join(ch * 2 for ch in c)
    return "#FF" + c.upper()


def rect_path(el):
    x, y = float(el.get("x", 0)), float(el.get("y", 0))
    w, h = float(el.get("width")), float(el.get("height"))
    r = float(el.get("rx", 0))
    if not r:
        return f"M{x:g},{y:g}H{x + w:g}V{y + h:g}H{x:g}Z"
    a = f"A{r:g},{r:g} 0 0 1"
    return (f"M{x + r:g},{y:g}H{x + w - r:g}{a} {x + w:g},{y + r:g}V{y + h - r:g}"
            f"{a} {x + w - r:g},{y + h:g}H{x + r:g}{a} {x:g},{y + h - r:g}V{y + r:g}"
            f"{a} {x + r:g},{y:g}Z")


def path_data(el):
    if tag(el) == "rect":
        return rect_path(el)
    lines = [" ".join(line.split()) for line in el.get("d").strip().splitlines()]
    return "\n            ".join(line for line in lines if line)


def gradients(root):
    found = {}
    for g in root.iter(f"{{{SVG_NS}}}linearGradient"):
        stops = [(num(s.get("offset")), color(s.get("stop-color")))
                 for s in g.iter(f"{{{SVG_NS}}}stop")]
        found[g.get("id")] = ({k: num(g.get(k)) for k in ("x1", "y1", "x2", "y2")}, stops)
    return found


def drawable_path(d, fill, rule, grads, indent="    "):
    i = indent
    attrs = ""
    if rule == "evenodd":
        attrs += f'\n{i}    android:fillType="evenOdd"'
    m = re.fullmatch(r"url\(#(.+)\)", fill)
    if not m:
        return (f'{i}<path\n{i}    android:fillColor="{color(fill)}"{attrs}\n'
                f'{i}    android:pathData="{d}" />\n')
    xy, stops = grads[m.group(1)]
    items = "".join(f'{i}            <item android:offset="{o}" android:color="{c}" />\n'
                    for o, c in stops)
    return (f'{i}<path{attrs}\n{i}    android:pathData="{d}">\n'
            f'{i}    <aapt:attr name="android:fillColor">\n'
            f'{i}        <gradient\n'
            f'{i}            android:type="linear"\n'
            f'{i}            android:startX="{xy["x1"]}"\n{i}            android:startY="{xy["y1"]}"\n'
            f'{i}            android:endX="{xy["x2"]}"\n{i}            android:endY="{xy["y2"]}">\n'
            f'{items}{i}        </gradient>\n{i}    </aapt:attr>\n{i}</path>\n')


def layer_xml(group, grads, name):
    body = ""
    for el in group:
        if el.tag is ET.Comment:
            text = "\n         ".join(line.strip() for line in el.text.strip().splitlines())
            body += f"    <!-- {text} -->\n"
        elif tag(el) == "g":  # a group's fill is shared: its shapes become one path
            d = "\n            ".join(path_data(c) for c in el if tag(c) in ("rect", "path"))
            body += drawable_path(d, el.get("fill"), el.get("fill-rule"), grads)
        elif tag(el) in ("rect", "path"):
            body += drawable_path(path_data(el), el.get("fill"), el.get("fill-rule"), grads)
    aapt = '\n    xmlns:aapt="http://schemas.android.com/aapt"' if "aapt:attr" in body else ""
    return (
        '<?xml version="1.0" encoding="utf-8"?>\n'
        f"<!-- Launcher icon {name} (#368). GENERATED by docs/icon-source/make_icons.py from the\n"
        f'     "{name}" layer of docs/icon-source/icon.svg; edit that and run it again. -->\n'
        f'<vector xmlns:android="http://schemas.android.com/apk/res/android"{aapt}\n'
        '    android:width="108dp"\n    android:height="108dp"\n'
        '    android:viewportWidth="108"\n    android:viewportHeight="108">\n'
        f"{body}</vector>\n"
    )


def browser():
    for exe in (shutil.which("chrome"), shutil.which("msedge"),
                r"C:\Program Files\Google\Chrome\Application\chrome.exe",
                r"C:\Program Files (x86)\Microsoft\Edge\Application\msedge.exe",
                "/usr/bin/google-chrome", "/usr/bin/chromium"):
        if exe and os.path.exists(exe):
            return exe
    raise SystemExit("Needs Chrome, Edge or Chromium to draw the SVGs.")


def render(svg_text, width, height, out):
    """Draws an SVG at width x height px on a transparent page with a headless browser."""
    with tempfile.TemporaryDirectory(ignore_cleanup_errors=True) as tmp:
        page = pathlib.Path(tmp) / "page.html"
        page.write_text(
            "<!doctype html><html><body style='margin:0;background:transparent;overflow:hidden'>"
            + svg_text + "</body></html>", encoding="utf-8")
        shot = pathlib.Path(tmp) / "shot.png"
        subprocess.run([browser(), "--headless=new", "--disable-gpu", "--hide-scrollbars",
                        "--force-device-scale-factor=1", "--default-background-color=00000000",
                        f"--window-size={width},{height}", f"--screenshot={shot}",
                        page.as_uri()], check=True, capture_output=True)
        with Image.open(shot) as im:
            im.convert("RGBA").crop((0, 0, width, height)).save(out)


def sized(svg_root, view_box, width, height):
    """icon.svg without its hidden monochrome layer, framed to view_box at the given size."""
    root = ET.fromstring(ET.tostring(svg_root))
    for g in list(root):
        if g.get("id") == "monochrome":
            root.remove(g)
    root.set("viewBox", view_box)
    root.set("width", str(width))
    root.set("height", str(height))
    root.set("style", "display:block")
    return ET.tostring(root, encoding="unicode")


def mask(size, shape):
    """Antialiased rounded-square or circle mask, drawn 4x larger and scaled down."""
    big = size * 4
    m = Image.new("L", (big, big), 0)
    d = ImageDraw.Draw(m)
    if shape == "round":
        d.ellipse((0, 0, big - 1, big - 1), fill=255)
    else:  # Android 7's rounded square: corner radius 16/72 of the side
        d.rounded_rectangle((0, 0, big - 1, big - 1), radius=big * 16 / 72, fill=255)
    return m.resize((size, size), Image.LANCZOS)


def pngs(root):
    with tempfile.TemporaryDirectory(ignore_cleanup_errors=True) as tmp:
        full = pathlib.Path(tmp) / "icon.png"
        render(sized(root, "18 18 72 72", RENDER, RENDER), RENDER, RENDER, full)
        with Image.open(full) as im:
            icon = im.convert("RGBA")
    icon.resize((512, 512), Image.LANCZOS).convert("RGB").save(HERE / "playstore-icon-512.png")
    for density, px in MIPMAPS.items():
        small = icon.resize((px, px), Image.LANCZOS)
        for suffix, shape in (("", "square"), ("_round", "round")):
            out = small.copy()
            out.putalpha(mask(px, shape))
            out.save(RES / f"mipmap-{density}" / f"ic_launcher{suffix}.png", optimize=True)


def feature_graphic(root, source):
    """Copies icon.svg's book (gradients + foreground) between feature-graphic.svg's markers,
    then renders it. The book's own cross shows the feature graphic's background through."""
    defs = root.find(f"{{{SVG_NS}}}defs")
    keep = [g for g in defs if g.get("id") != "bg"]
    fg = next(g for g in root if g.get("id") == "foreground")
    inner = "".join(ET.tostring(e, encoding="unicode") for e in keep)
    book = (f"<defs>{inner}</defs>" + ET.tostring(fg, encoding="unicode"))
    book = re.sub(r'\s+xmlns(:\w+)?="[^"]*"', "", book)
    book = re.sub(r"<!--.*?-->", "", book, flags=re.S)
    book = re.sub(r"\s*\n\s*", " ", book)
    text = FEATURE.read_text(encoding="utf-8")
    text, n = re.subn(r"(<!-- icon:begin[^>]*-->).*?(<!-- icon:end -->)",
                      lambda m: f"{m.group(1)}\n    {book}\n    {m.group(2)}", text, flags=re.S)
    if n != 1:
        raise SystemExit("feature-graphic.svg needs one <!-- icon:begin --> ... <!-- icon:end -->")
    FEATURE.write_text(text, encoding="utf-8")
    with tempfile.TemporaryDirectory(ignore_cleanup_errors=True) as tmp:
        shot = pathlib.Path(tmp) / "feature.png"
        render(text, 1024, 500, shot)
        with Image.open(shot) as im:
            im.convert("RGB").save(FEATURE.with_suffix(".png"), optimize=True)


def main():
    ET.register_namespace("", SVG_NS)
    root = ET.parse(SOURCE, ET.XMLParser(target=ET.TreeBuilder(insert_comments=True))).getroot()
    grads = gradients(root)
    for g in root:
        if tag(g) == "g":
            name = g.get("id")
            (RES / "drawable" / f"ic_launcher_{name}.xml").write_text(
                layer_xml(g, grads, name), encoding="utf-8")
    plain = ET.parse(SOURCE).getroot()
    pngs(plain)
    make_splash_icons.main()
    feature_graphic(plain, SOURCE)


if __name__ == "__main__":
    main()
